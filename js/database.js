const matchGroup = (cardValues, filters, mode) => {
  if (filters.size === 0) return true;

  const filtersArray = [...filters];

  if (mode === 'no-filter') return true;
  if (mode === 'any') return filtersArray.some((v) => cardValues?.includes(v));
  if (mode === 'all') return filtersArray.every((v) => cardValues?.includes(v));

  if (mode === 'exactly') {
    // Group filters
    const filtersGroups = groupTags(filtersArray);
    const cardGroups = groupTags(cardValues);

    for (const [group, filtersSet] of filtersGroups) {
      const cardSet = cardGroups.get(group);

      // Fails if not an exact match
      if (!cardSet || cardSet.size !== filtersSet.size) return false;
      for (const filter of filtersSet) if (!cardSet.has(filter)) return false;
    }
    return true;
  }
};

const filterCards = () => {
  return cards.filter((card) =>
    Object.entries(state).every(([group, { filters, mode }]) => {
      let cardValues;
      if (group === 'spawn') {
        cardValues = card.spawns;
      } else if (group === 'style') {
        cardValues = card.styles;
      } else {
        cardValues = card.tags;
      }
      return matchGroup(cardValues, filters, mode);
    })
  );
};

const cardContainer = document.getElementById('card-container');

const secretStyleBtn = document.querySelector('.btn-secret-style');
const sr2StyleBtn = document.querySelector('.btn-sr2-style');

const renderCards = (items) => {
  // No card matches
  if (!items || items.length === 0) {
    cardContainer.innerHTML = '';
    return;
  }

  cardContainer.innerHTML = items
    .map((item) => {
      const isSecretStyleToggledOn =
        secretStyleBtn.classList.contains('toggledOn');
      const isSr2StyleToggledOn = sr2StyleBtn.classList.contains('toggledOn');

      const hasRadiantAndToggledOn =
        isSecretStyleToggledOn && isSr2StyleToggledOn && item['radiant-icon'];
      const hasSR2AndToggledOn = isSr2StyleToggledOn && item['sr2-icon'];
      const hasSecretStyleAndToggledOn =
        isSecretStyleToggledOn && item['secret-style-icon'];

      // Select style icon
      let iconSrc;
      if (hasRadiantAndToggledOn) {
        iconSrc = item['radiant-icon'];
      } else if (hasSR2AndToggledOn) {
        iconSrc = item['sr2-icon'];
      } else if (hasSecretStyleAndToggledOn) {
        iconSrc = item['secret-style-icon'];
      } else {
        iconSrc = item['icon'];
      }

      // Select style name
      let styleName;
      if (hasRadiantAndToggledOn) {
        styleName = 'Radiant';
      } else if (hasSR2AndToggledOn) {
        styleName = 'Slime Rancher 2';
      } else if (isSecretStyleToggledOn && item['secret-style-name']) {
        styleName = item['secret-style-name'];
      } else {
        styleName = '';
      }

      let radiantVars = '';

      // Random radiant gradient values
      if (hasRadiantAndToggledOn) {
        const baseColors = ['#f8f08a', '#f6c6e8', '#d8c9ff', '#8eefff'];

        // Random Order
        const colors = [...baseColors].sort(() => Math.random() - 0.5);

        // Random stop positions
        const p1 = 15 + Math.random() * 15; // 15–30
        const p2 = p1 + 15 + Math.random() * 15; // 30–60
        const p3 = p2 + 15 + Math.random() * 15; // 60–90

        radiantVars = `
          --angle:${Math.floor(Math.random() * 360)}deg;
          --c1:${colors[0]};
          --c2:${colors[1]};
          --c3:${colors[2]};
          --c4:${colors[3]};
          --p1:${p1}%;
          --p2:${p2}%;
          --p3:${p3}%;
        `;
      }

      className = '';
      styleAttr = '';

      if (hasRadiantAndToggledOn) {
        // Distinguish Slime Rancher 2 "Radiant" styling from Rad Slime "Radiant" styling
        className = 'style-radiant';
        styleAttr = radiantVars;
      } else if (hasSR2AndToggledOn) {
        className = 'style-sr2';
      } else {
        className = styleName
          ? 'secret-style-' + styleName.toLowerCase().replace(/\s+/g, '-')
          : '';
      }

      // Render cards
      return `
      <div class="card">
        <img src="${iconSrc}" alt="${item.name}" class="card-img-main" />
          <h2 class="card-name ${item.name.toLowerCase().replace(/\s+/g, '-')}">${item.name}</h2>
          <p class="card-style-name ${className}" style="${styleAttr}">${styleName}</p>
          <div class="card-tags">
            ${(item.tags ?? [])
              .map(
                (tag) =>
                  `<span class="tag tag-${tag.toLowerCase()}" style="--tag-color: var(--${tag}-color)">${titleCaseSlug(tag)}</span>`
              )
              .join('')}
          </div>

          <div class="card-spawn-tags">
            ${(item.spawns ?? [])
              .map(
                (spawn) =>
                  `<span class="tag tag-${spawn.toLowerCase()}" style="--tag-color: var(--${spawn}-color)">${titleCaseSlug(spawn)}</span>`
              )
              .join('')}
          </div>
        </div>
      `;
    })
    .join('');
};

const params = new URLSearchParams(location.search);

for (const [group, value] of params.entries()) {
  const [mode, filterString] = value.split(':');

  // Set state
  state[group].mode = mode;
  state[group].filters = new Set(filterString.split(','));

  // Set mode btn toggles
  modeBtns.forEach((btn) => {
    btn.classList.remove('toggledOn');

    if (btn.closest('.filter-bar').dataset.group === group) {
      if (btn.dataset.mode === mode) {
        btn.classList.add('toggledOn');
      }
    }
  });

  // Set filter btn toggles
  filterBtns.forEach((btn) => {
    btn.classList.remove('toggledOn');

    if (btn.closest('.filter-bar').dataset.group === group) {
      if (state[group].filters.has(btn.dataset.category)) {
        btn.classList.add('toggledOn');
      } else if (btn.dataset.category === 'style') {
        if (
          state[group].filters.has('secret') ||
          state[group].filters.has('radiant')
        ) {
          btn.classList.add('toggledOn');
        }
      }
    }
  });
}

