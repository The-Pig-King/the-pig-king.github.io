const groupTags = (tags = []) => {
  const grouped = new Map();

  for (const tag of tags) {
    const group = tagGroups[tag] ?? 'other';

    if (!grouped.has(group)) {
      grouped.set(group, new Set());
    }
    grouped.get(group).add(tag);
  }
  return grouped;
};

